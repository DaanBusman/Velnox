#!/usr/bin/env bash
#
# Custom roles (ADR-054), asserted against a running stack.
#
# What a custom role may hold — nothing its maker lacks, never system settings
# or making roles, and for customers no more than a Tenant Administrator — and
# the two holes in granting a role that were closed with it: an MSP-only role
# given to a customer's account, and a role stronger than its grantor's own.
# Then a custom role doing its job: a customer's account given it can do what
# it says, and nothing else, and loses what it loses when the role changes.
#
#   VELNOX_ADMIN_EMAIL=... VELNOX_ADMIN_PASSWORD=... ./scripts/verify-roles.sh [base-url]
#
# Everything it creates is named with a run-specific prefix; the accounts are
# disabled, the tenant archived and the roles removed at the end.

set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ROOT_NATIVE="$(cd "$ROOT" && { pwd -W 2>/dev/null || pwd; })"
COMPOSE=(docker compose -f "$ROOT_NATIVE/deploy/compose/docker-compose.yml" --env-file "$ROOT_NATIVE/.env")
psql_at() { "${COMPOSE[@]}" exec -T postgres psql -U velnox -d velnox -v ON_ERROR_STOP=1 -Atc "$1"; }
BASE="${1:-https://localhost}"
RUN="vr$(date +%s)"

PASS=0
FAIL=0

green() { printf '\033[0;32m  ok  \033[0m %s\n' "$*"; }
red() { printf '\033[0;31m FAIL \033[0m %s\n' "$*"; }
info() { printf '\033[0;36m----\033[0m %s\n' "$*"; }

check() {
  local name="$1" expected="$2" actual="$3"
  if [[ "$expected" == "$actual" ]]; then
    green "$name"
    PASS=$((PASS + 1))
  else
    red "$name (expected ${expected}, got ${actual})"
    FAIL=$((FAIL + 1))
  fi
}

# Reads a dotted path out of JSON on stdin. jq when it is there, node otherwise:
# a Debian host often has neither node nor jq, and a Windows workstation often
# has node and no jq.
if command -v jq >/dev/null 2>&1; then
  json() { jq -r --arg p "$1" '($p | split(".")) as $k | getpath($k) // empty' 2>/dev/null; }
elif command -v node >/dev/null 2>&1; then
  json() {
    node -e '
      let raw = "";
      process.stdin.on("data", (c) => (raw += c));
      process.stdin.on("end", () => {
        try {
          let value = JSON.parse(raw);
          for (const key of process.argv[1].split(".")) value = value?.[key];
          if (value !== undefined && value !== null) process.stdout.write(String(value));
        } catch { /* no output is the answer */ }
      });
    ' "$1" 2>/dev/null
  }
else
  echo "Needs jq or node to read JSON responses." >&2
  exit 1
fi

# Encode arguments as a JSON object: keys and values alternating.
#
# Only sign_in needs this, and it needs it badly: the operator's password used to
# be pasted straight into a JSON string literal, so one holding a double quote or
# a backslash produced a malformed body and a 401 indistinguishable from a wrong
# password. Every other password here is generated by this script from a safe
# alphabet. Values arrive as argv, so they survive the shell untouched too.
if command -v jq >/dev/null 2>&1; then
  json_object() {
    jq -cn --args '$ARGS.positional
      | [range(0; length; 2) as $i | {(.[$i]): .[$i + 1]}]
      | add' "$@"
  }
else
  json_object() {
    node -e '
      const out = {};
      for (let i = 1; i < process.argv.length; i += 2) out[process.argv[i]] = process.argv[i + 1];
      process.stdout.write(JSON.stringify(out));
    ' "$@"
  }
fi

# ---------------------------------------------------------------------------
# One signed-in identity per cookie jar
# ---------------------------------------------------------------------------

JARS="$(mktemp -d)"
trap 'rm -rf "$JARS"' EXIT

# Method, path, body, and the jar to use. Prints the body; records the status.
#
# The status goes to a file rather than a variable, because almost every call is
# read as `X="$(call …)"` — a subshell, whose variables are gone by the time the
# caller looks. Written the obvious way first, this file reported 35 of 35
# passing while every status assertion was in fact comparing against the status
# of the *first* request, which happened to be a 201. A harness that can pass for
# the wrong reason is worse than no harness.
STATUS_FILE="${JARS}/status"

call() {
  local who="$1" method="$2" path="$3" body="${4:-}"
  local jar="${JARS}/${who}.jar"
  local csrf=""

  # Double-submit: the header has to echo the cookie, which is why the jar is
  # read rather than a token being remembered.
  if [[ -f "$jar" ]]; then
    csrf="$(awk '$6 == "velnox_csrf" { print $7 }' "$jar" | tail -1)"
  fi

  local response
  response="$(curl --silent --insecure --max-time 20 \
    --cookie "$jar" --cookie-jar "$jar" \
    --request "$method" \
    --header 'accept: application/json' \
    ${body:+--header 'content-type: application/json'} \
    ${csrf:+--header "x-velnox-csrf: ${csrf}"} \
    ${body:+--data "$body"} \
    --write-out '\n%{http_code}' \
    "${BASE}${path}")"

  printf '%s' "${response##*$'\n'}" > "$STATUS_FILE"
  printf '%s' "${response%$'\n'*}"
}

# The status of the most recent `call`, wherever it ran.
last_status() { cat "$STATUS_FILE"; }

status() {
  call "$@" >/dev/null
  last_status
}

sign_in() {
  local who="$1" email="$2" password="$3"
  rm -f "${JARS}/${who}.jar"
  call "$who" POST /api/v1/auth/login \
    "$(json_object email "$email" password "$password")" >/dev/null
  last_status
}

# ---------------------------------------------------------------------------
# Get an administrator
# ---------------------------------------------------------------------------

# Long, mixed, and not reused between runs. It is written to stdout once so a
# failed run can be investigated, and it belongs to a throwaway account.
PASSWORD="Vx-${RUN}-$(od -An -N6 -tx1 /dev/urandom | tr -d ' \n')"

INITIALIZED="$(call anon GET /api/v1/setup/status | json initialized)"

if [[ "$INITIALIZED" != "true" ]]; then
  info "Running setup, because this installation has none."
  call anon POST /api/v1/setup/initialize \
    "{\"organisationName\":\"Roles Verification\",\"displayName\":\"Verification Admin\",\"email\":\"${RUN}-admin@example.invalid\",\"password\":\"${PASSWORD}\"}" >/dev/null
  check "setup: initialize accepted" 201 "$(last_status)"
  ADMIN_EMAIL="${RUN}-admin@example.invalid"
  ADMIN_PASSWORD="$PASSWORD"
else
  ADMIN_EMAIL="${VELNOX_ADMIN_EMAIL:-}"
  ADMIN_PASSWORD="${VELNOX_ADMIN_PASSWORD:-}"
  if [[ -z "$ADMIN_EMAIL" || -z "$ADMIN_PASSWORD" ]]; then
    echo "This installation is already set up. Provide an administrator:" >&2
    echo "  VELNOX_ADMIN_EMAIL=... VELNOX_ADMIN_PASSWORD=... $0 ${BASE}" >&2
    exit 2
  fi
fi

check "admin: signs in" 200 "$(sign_in msp "$ADMIN_EMAIL" "$ADMIN_PASSWORD")"

role_id() { call msp GET /api/v1/roles | node -e 'let r="";process.stdin.on("data",c=>r+=c).on("end",()=>{const x=(JSON.parse(r).roles||[]).find(o=>o.key===process.argv[1]);if(x)process.stdout.write(x.id)})' "$1"; }
role_perms() { call msp GET /api/v1/roles | node -e 'let r="";process.stdin.on("data",c=>r+=c).on("end",()=>{const x=(JSON.parse(r).roles||[]).find(o=>o.id===process.argv[1]);if(x)process.stdout.write(x.permissions.join(","))})' "$1"; }
me_perms() { call "$1" GET /api/v1/auth/me | node -e 'let r="";process.stdin.on("data",c=>r+=c).on("end",()=>{try{process.stdout.write(JSON.parse(r).user.permissions.join(","))}catch(e){}})'; }
role_body() { # name mspOnly perms(comma)
  node -e 'process.stdout.write(JSON.stringify({name:process.argv[1],mspOnly:process.argv[2]==="true",permissions:process.argv[3]?process.argv[3].split(","):[]}))' "$1" "$2" "$3"
}
# The status and the error code of one call, read after it finished.
status_code() {
  local body
  body="$(call "$@")"
  printf '%s %s' "$(last_status)" "$(printf '%s' "$body" | json error.code)"
}
MSP_ROOT="$(psql_at "SELECT id FROM tenants WHERE kind = 'MSP_ROOT';")"

info "What a custom role may hold."
R="$(call msp POST /api/v1/roles "$(role_body "${RUN} Update operator" false "clusters.read,updates.execute")")"
check "make: a role customers may be given" 201 "$(last_status)"
CUSTOM="$(printf '%s' "$R" | json id)"
check "make: it is a custom role, not a system one" "false" "$(printf '%s' "$R" | json isSystem)"
check "make: can change brings can read with it" "clusters.read,updates.read,updates.execute" "$(role_perms "$CUSTOM")"
check "refused: system settings" "400 role.invalid" "$(status_code msp POST /api/v1/roles "$(role_body "${RUN} x1" true "system.manage")")"
check "refused: making roles" "400 role.invalid" "$(status_code msp POST /api/v1/roles "$(role_body "${RUN} x2" true "roles.manage")")"
check "refused: the ISO library, in a role customers may be given" "400 role.invalid" "$(status_code msp POST /api/v1/roles "$(role_body "${RUN} x3" false "library.manage")")"
check "but in an MSP-only role it may" 201 "$(status msp POST /api/v1/roles "$(role_body "${RUN} Librarian" true "library.manage")")"
check "refused: a permission that does not exist, named" "400" "$(status msp POST /api/v1/roles "$(role_body "${RUN} x4" true "clusters.destroy")")"
check "refused: a second role with the same name" 409 "$(status msp POST /api/v1/roles "$(role_body "${RUN} update OPERATOR" true "clusters.read")")"
check "refused: changing a system role" "409 role.system" "$(status_code msp PUT "/api/v1/roles/$(role_id msp_read_only)" "$(role_body "Changed" true "clusters.read")")"

info "An MSP Administrator: makes roles, but no stronger than itself."
TENANT="$(call msp POST /api/v1/tenants "{\"name\":\"${RUN} Customer\"}" | json id)"
check "a customer tenant" 201 "$(last_status)"
ADMIN2_EMAIL="${RUN}-mspadmin@example.invalid"
ADMIN2="$(call msp POST /api/v1/users "{\"email\":\"${ADMIN2_EMAIL}\",\"displayName\":\"MSP Administrator\",\"password\":\"${PASSWORD}\",\"tenantId\":\"${MSP_ROOT}\"}" | json id)"
check "an MSP Administrator" 201 "$(status msp POST "/api/v1/users/${ADMIN2}/role-assignments" "{\"roleId\":\"$(role_id msp_administrator)\",\"scopeType\":\"GLOBAL\"}")"
COLLEAGUE="$(call msp POST /api/v1/users "{\"email\":\"${RUN}-colleague@example.invalid\",\"displayName\":\"Colleague\",\"password\":\"${PASSWORD}\",\"tenantId\":\"${MSP_ROOT}\"}" | json id)"
CUSTOMER_EMAIL="${RUN}-customer@example.invalid"
CUSTOMER="$(call msp POST /api/v1/users "{\"email\":\"${CUSTOMER_EMAIL}\",\"displayName\":\"Customer Operator\",\"password\":\"${PASSWORD}\",\"tenantId\":\"${TENANT}\"}" | json id)"
check "a customer's account" 201 "$(last_status)"
check "mspadmin: signs in" 200 "$(sign_in mspadmin "$ADMIN2_EMAIL" "$PASSWORD")"
check "mspadmin: cannot put support.manage, which it lacks, in a role" "400 role.invalid" "$(status_code mspadmin POST /api/v1/roles "$(role_body "${RUN} x5" true "support.manage")")"
check "mspadmin: makes a role from what it holds" 201 "$(status mspadmin POST /api/v1/roles "$(role_body "${RUN} Placement" true "placement.manage")")"
check "closed: mspadmin cannot make a colleague MSP Super Administrator" "403 role.beyond_grantor" "$(status_code mspadmin POST "/api/v1/users/${COLLEAGUE}/role-assignments" "{\"roleId\":\"$(role_id msp_super_administrator)\",\"scopeType\":\"GLOBAL\"}")"
check "closed: nor itself" "403 role.beyond_grantor" "$(status_code mspadmin POST "/api/v1/users/${ADMIN2}/role-assignments" "{\"roleId\":\"$(role_id msp_super_administrator)\",\"scopeType\":\"GLOBAL\"}")"
check "closed: an MSP-only role for a customer's account, at its tenant" "409 role.msp_only" "$(status_code msp POST "/api/v1/users/${CUSTOMER}/role-assignments" "{\"roleId\":\"$(role_id msp_engineer)\",\"scopeType\":\"TENANT\",\"scopeId\":\"${TENANT}\"}")"
TRIGGER="$(psql_at "INSERT INTO role_assignments (id, user_id, role_id, scope_type, scope_id, tenant_id) VALUES (gen_random_uuid(), '${CUSTOMER}', '$(role_id msp_engineer)', 'TENANT', '${TENANT}', '${TENANT}');" 2>&1)"
if [[ "$TRIGGER" == *"MSP-only role can only be assigned"* ]]; then REFUSED=yes; else REFUSED="$(printf '%s' "$TRIGGER" | head -c 200)"; fi
check "closed: and the database refuses it too" yes "$REFUSED"

info "A custom role doing its job for a customer."
check "grant: the custom role, at the customer's tenant" 201 "$(status msp POST "/api/v1/users/${CUSTOMER}/role-assignments" "{\"roleId\":\"${CUSTOM}\",\"scopeType\":\"TENANT\",\"scopeId\":\"${TENANT}\"}")"
check "customer: signs in" 200 "$(sign_in customer "$CUSTOMER_EMAIL" "$PASSWORD")"
check "customer: holds what the role says" "clusters.read,updates.execute,updates.read" "$(me_perms customer)"
check "customer: may read clusters" 200 "$(status customer GET /api/v1/clusters)"
check "customer: may not add one" 403 "$(status customer POST /api/v1/clusters '{"tenantId":"'"${TENANT}"'","name":"x","host":"192.0.2.1","port":8006,"fingerprint":"AA","auth":{"kind":"API_TOKEN","tokenId":"a@pve!b","secret":"c"}}')"
check "change: running updates taken out of the role" 200 "$(status msp PUT "/api/v1/roles/${CUSTOM}" "$(role_body "${RUN} Update operator" false "clusters.read,updates.read")")"
check "customer: its session ends with the change" 401 "$(status customer GET /api/v1/auth/me)"
sign_in customer "$CUSTOMER_EMAIL" "$PASSWORD" >/dev/null
check "customer: and holds the role as it is now" "clusters.read,updates.read" "$(me_perms customer)"
check "refused: made MSP-only while a customer holds it" "409 role.in_use" "$(status_code msp PUT "/api/v1/roles/${CUSTOM}" "$(role_body "${RUN} Update operator" true "clusters.read")")"
check "refused: removed while held" "409 role.in_use" "$(status_code msp DELETE "/api/v1/roles/${CUSTOM}")"
check "refused: a customer cannot make roles" 403 "$(status customer POST /api/v1/roles "$(role_body "${RUN} x6" false "clusters.read")")"

info "Recorded, and cleaned up."
ASSIGNMENT="$(call msp GET /api/v1/users | node -e 'let r="";process.stdin.on("data",c=>r+=c).on("end",()=>{const u=(JSON.parse(r).users||[]).find(x=>x.id===process.argv[1]);const a=u&&u.roles.find(x=>x.roleId===process.argv[2]);if(a)process.stdout.write(a.assignmentId)})' "$CUSTOMER" "$CUSTOM")"
check "revoke: the customer's grant" 204 "$(status msp DELETE "/api/v1/users/${CUSTOMER}/role-assignments/${ASSIGNMENT}")"
check "remove: the role, once nobody holds it" 204 "$(status msp DELETE "/api/v1/roles/${CUSTOM}")"
for name in "${RUN} Librarian" "${RUN} Placement"; do
  ID="$(call msp GET /api/v1/roles | node -e 'let r="";process.stdin.on("data",c=>r+=c).on("end",()=>{const x=JSON.parse(r).roles.find(o=>o.name===process.argv[1]);if(x)process.stdout.write(x.id)})' "$name")"
  [[ -n "$ID" ]] && call msp DELETE "/api/v1/roles/${ID}" >/dev/null
done
check "audit: made, changed and removed, each recorded" "1 1 1" "$(psql_at "SELECT count(*) FILTER (WHERE action = 'role.created'), count(*) FILTER (WHERE action = 'role.updated'), count(*) FILTER (WHERE action = 'role.deleted') FROM audit_events WHERE resource_id = '${CUSTOM}';" | tr '|' ' ')"
for id in "$ADMIN2" "$COLLEAGUE" "$CUSTOMER"; do call msp PATCH "/api/v1/users/${id}/status" '{"status":"DISABLED"}' >/dev/null; done
check "cleanup: the customer tenant archives" 200 "$(status msp DELETE "/api/v1/tenants/${TENANT}")"

echo
if [[ $FAIL -eq 0 ]]; then
  printf '\033[0;32m%s checks passed.\033[0m\n' "$PASS"
else
  printf '\033[0;31m%s passed, %s failed.\033[0m\n' "$PASS" "$FAIL"
  exit 1
fi
